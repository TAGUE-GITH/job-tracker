-- Schema initial de Taguora (PostgreSQL en production, H2 en mode PostgreSQL en developpement et en tests).
-- Les valeurs des enums (statut, type d'etape, type de document) sont controlees par le code Java :
-- pas de contrainte CHECK, pour pouvoir ajouter une valeur sans migration.

create table users (
    id bigint generated by default as identity,
    nom varchar(255) not null,
    email varchar(255) not null,
    password varchar(255) not null,
    telephone varchar(30),
    adresse varchar(300),
    ville varchar(100),
    constraint pk_users primary key (id),
    constraint uk_users_email unique (email)
);

create table document (
    id bigint generated by default as identity,
    nom_fichier varchar(255) not null,
    type varchar(255) not null,
    content_type varchar(255),
    date_ajout date not null,
    user_id bigint not null,
    constraint pk_document primary key (id),
    constraint fk_document_user foreign key (user_id) references users (id)
);

create table document_contenu (
    document_id bigint not null,
    donnees bytea not null,
    constraint pk_document_contenu primary key (document_id),
    constraint fk_document_contenu_document foreign key (document_id) references document (id)
);

create table candidature (
    id bigint generated by default as identity,
    nom_entreprise varchar(255) not null,
    poste varchar(255) not null,
    lien_offre varchar(1000),
    texte_offre text,
    date_candidature date not null,
    statut varchar(255) not null,
    user_id bigint not null,
    cv_id bigint,
    lettre_id bigint,
    constraint pk_candidature primary key (id),
    constraint fk_candidature_user foreign key (user_id) references users (id),
    constraint fk_candidature_cv foreign key (cv_id) references document (id),
    constraint fk_candidature_lettre foreign key (lettre_id) references document (id)
);

create table etape (
    id bigint generated by default as identity,
    type varchar(255) not null,
    date_etape date not null,
    notes text,
    candidature_id bigint not null,
    constraint pk_etape primary key (id),
    constraint fk_etape_candidature foreign key (candidature_id) references candidature (id)
);

create index idx_candidature_user on candidature (user_id);
create index idx_document_user on document (user_id);
create index idx_etape_candidature on etape (candidature_id);
