-- Version des jetons de connexion : l'incrementer deconnecte toutes les sessions de l'utilisateur
-- (changement ou reinitialisation du mot de passe).
alter table users add column if not exists version_jeton integer default 0 not null;

-- Liens "mot de passe oublie" : seul le hash SHA-256 du jeton est stocke, jamais le jeton lui-meme.
create table jeton_reinitialisation (
    id bigint generated by default as identity,
    user_id bigint not null,
    hash varchar(64) not null,
    expiration timestamp not null,
    date_creation timestamp not null,
    utilise boolean default false not null,
    constraint pk_jeton_reinitialisation primary key (id),
    constraint uk_jeton_reinitialisation_hash unique (hash),
    constraint fk_jeton_reinitialisation_user foreign key (user_id) references users (id)
);

create index idx_jeton_reinitialisation_user on jeton_reinitialisation (user_id);
