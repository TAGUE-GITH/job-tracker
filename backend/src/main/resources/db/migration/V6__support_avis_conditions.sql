-- Messages envoyes depuis la page Contact (visiteurs ou utilisateurs connectes)
create table message_contact (
    id bigint generated by default as identity,
    user_id bigint,
    nom varchar(100) not null,
    email varchar(255) not null,
    categorie varchar(20) not null,
    sujet varchar(150) not null,
    message varchar(5000) not null,
    date_creation timestamp not null,
    traite boolean default false not null,
    constraint pk_message_contact primary key (id),
    constraint fk_message_contact_user foreign key (user_id) references users (id) on delete set null
);

-- Avis des utilisateurs sur l'application (note de 1 a 5 et commentaire)
create table avis (
    id bigint generated by default as identity,
    user_id bigint not null,
    note integer not null,
    commentaire varchar(2000),
    date_creation timestamp not null,
    constraint pk_avis primary key (id),
    constraint fk_avis_user foreign key (user_id) references users (id) on delete cascade
);

-- Date d'acceptation des conditions d'utilisation (null pour les comptes crees avant leur mise en place)
alter table users add column if not exists conditions_acceptees_le timestamp;
